"""figinset copies coordinates unchanged, and refuses an inset that hides data."""

import copy
import re

import pytest

from pysimcount import figdrop, figinset, figuniform

# pfchilds-style figure: one formula, measured n = 4, 10 then extrapolated n = 100, 1000.
TEX = r"""% Generated by pysimcount.pfchilds -- do not edit; regenerate instead.
% figure: X -- test
\begin{tikzpicture}
  \begin{loglogaxis}[
    xtick={10,100}, xticklabels={10,100},
    xmin=1, xmax=1000,
  ]
    % suzuki4: measured n, mean over seeds, bars min..max over seeds
    \addplot[red, solid, mark=square*, mark size=2.2pt, mark options={solid, fill=red}, error bars/.cd, y dir=both, y explicit, error bar style={solid}] coordinates {
      (4,1000) += (0,10) -= (0,20)
      (10,10000) += (0,30) -= (0,40)
    };
    \addlegendentry{Suzuki S4}
    % suzuki4: extrapolated, r = ceil(1 n^2), per step = 42 n + 0; bars min..max of per-seed fits
    \addplot[red, dashed, mark=square*, mark size=2.2pt, mark options={solid, fill=white}, forget plot, error bars/.cd, y dir=both, y explicit, error bar style={solid}] coordinates {
      (10,10000)
      (100,1e+06) += (0,50) -= (0,60)
      (1000,1e+08) += (0,70) -= (0,80)
    };
    \addlegendimage{black, solid, mark=*, mark options={solid, fill=black}}
    \addlegendentry{measured $r$ (mean over seeds)}
    \addlegendimage{black, dashed, mark=*, mark options={solid, fill=white}}
    \addlegendentry{$r$ from power-law fit to mean measured $r$ (n = 5--10)}
  \end{loglogaxis}
\end{tikzpicture}
"""

# Main axis 10 cm x 10 cm over x, y = 1..1000, 1..1e10: data runs along the
# diagonal from about (2, 3) cm to (10, 8) cm, so the top left corner is empty.
FIG = {
    "main": {"width_cm": 10.0, "height_cm": 10.0, "xmin": 1, "xmax": 1000, "ymin": 1, "ymax": 1e10,
             "ylabel": "count", "main_error_bars": False, "mark_size": "1.5pt", "legend_columns": 2},
    "insets": [{"name": "small", "side": "above", "title": "small n", "xmin": 3, "xmax": 12, "ymin": 500, "ymax": 2e4,
                "at_cm": [1.2, 6.5], "width_cm": 3.0, "height_cm": 3.0, "xtick": [4, 10], "ytick": [1e3, 1e4]}],
}


def _fig(**inset_changes) -> dict:
    fig = copy.deepcopy(FIG)
    fig["insets"][0].update(inset_changes)
    return fig


def _axes(text: str) -> list[str]:
    return re.findall(r"\\begin\{loglogaxis\}.*?\\end\{loglogaxis\}", text, re.S)


def _coords(axis: str) -> list[tuple[str, str]]:
    return [(m.group(1), m.group(2)) for m in figdrop.COORD.finditer(axis.split("]\n", 1)[1])]


def test_log_position_by_hand():
    # 10 is halfway between 1 and 100 on a log axis
    assert figinset._log_frac(10, 1, 100) == pytest.approx(0.5)
    # y = 1e5 on 1..1e10 over 10 cm is at 5 cm; x = 1000 is the right edge
    assert figinset.main_position_cm(1000, 1e5, FIG["main"]) == pytest.approx((10.0, 5.0))


def test_tick_labels():
    assert figinset._tick_label(1e4) == "$10^{4}$"
    assert figinset._tick_label(5e3) == "$5{\\times}10^{3}$"
    with pytest.raises(ValueError, match="single digit"):
        figinset._tick_label(2.5e3)


def test_coordinates_are_the_source_coordinates_in_both_axes():
    main, inset = _axes(figinset.inset_text(TEX, "X.tex", FIG))
    source = [(m.group(1), m.group(2)) for m in figdrop.COORD.finditer(TEX)]
    assert _coords(inset) == source
    assert _coords(main.split("% zoom window")[0]) == source


def test_error_bars_only_where_asked():
    main, inset = _axes(figinset.inset_text(TEX, "X.tex", FIG))
    assert "+=" not in main and "error bars" not in main
    assert "(4,1000) += (0,10) -= (0,20)" in inset and "error bars" in inset
    keep = copy.deepcopy(FIG)
    keep["main"]["main_error_bars"] = True
    main, _ = _axes(figinset.inset_text(TEX, "X.tex", keep))
    assert "(4,1000) += (0,10) -= (0,20)" in main


def test_inset_adds_no_legend_entries():
    main, inset = _axes(figinset.inset_text(TEX, "X.tex", FIG))
    assert main.count("\\addlegendentry") == 3
    assert "\\addlegendentry" not in inset and "\\addlegendimage" not in inset
    # every inset plot must not enter the (absent) legend, or pgfplots warns per plot
    assert inset.count("\\addplot") == inset.count("forget plot") == 2
    assert "{Suzuki S4}" in main and "{extrapolated: $r$ from power-law fit" in main


def test_header_records_source_and_points_outside_the_window():
    text = figinset.inset_text(TEX, "X.tex", FIG)
    assert text.startswith(TEX.splitlines()[0])
    assert "% derived: X.tex with zoomed insets by pysimcount.figinset" in text and "source_sha256=" in text
    assert "not shown in this inset: none" in text
    tight = figinset.inset_text(TEX, "X.tex", _fig(ymax=5e3))
    # n = 10 appears in both the measured plot and the joining point of the extrapolated one
    assert "not shown in this inset: suzuki4 n=10, suzuki4 n=10" in tight


def test_stays_out_of_the_other_derivers_scope():
    text = figinset.inset_text(TEX, "X.tex", FIG)
    assert figuniform.in_scope(TEX) and not figuniform.in_scope(text)  # restyle assumes one axis
    assert figdrop.has_fixed_y(text)


@pytest.mark.parametrize("change, message", [
    (dict(at_cm=[3.0, 2.5], width_cm=4.0, height_cm=4.0), "covers data"),
    (dict(at_cm=[8.0, 0.8], width_cm=5.0), "leaves the plot area"),
    (dict(at_cm=[0.3, 6.5]), "leaves the plot area"),  # no room for its tick labels
    (dict(xmin=20, xmax=10), "empty window"),
    (dict(xmin=20, xmax=50), "no plotted point"),
])
def test_bad_inset_raises(change, message):
    with pytest.raises(ValueError, match=message):
        figinset.inset_text(TEX, "X.tex", _fig(**change))


def test_side_must_be_known():
    with pytest.raises(ValueError, match="side must be"):
        figinset.inset_text(TEX, "X.tex", _fig(side="left"))


def test_unexpected_content_in_axis_raises():
    with pytest.raises(ValueError, match="unexpected inside the axis"):
        figinset.inset_text(TEX.replace("\\addlegendentry{Suzuki S4}", "\\draw (0,0) -- (1,1);"), "X.tex", FIG)
