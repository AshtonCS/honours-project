"""Tests for the T-count slide figures (pysimcount.pftcount)."""

import csv

import pytest

from pysimcount import figdrop, pftcount


def test_t_per_rotation_by_hand():
    # np-main seed 1, S4, n = 4, ct: r = 53, R = 26n = 104 rotations per step,
    # eps_rot = 5e-4 / (53 * 104) -> T per rotation = 410,856 / 5,512.
    tpr, R = pftcount.t_per_rotation(410856, 53, 9.071117561683599e-08, 5e-4)
    assert R == 104 and tpr == pytest.approx(410856 / 5512)
    with pytest.raises(ValueError, match="multiple"):
        pftcount.t_per_rotation(410856, 53, 5e-4 / (53 * 104.5), 5e-4)


def test_line_fit_by_hand():
    a, b = pftcount.line_fit([1, 2, 3], [3, 5, 7])
    assert a == pytest.approx(2) and b == pytest.approx(1)


FIELDS = ["instance", "scheme", "n", "r", "r_source", "gatebase", "merged", "t_total", "eps_rot", "eps_synth"]


def _run(d, rows):
    d.mkdir(parents=True)
    with open(d / "results.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=FIELDS)
        w.writeheader()
        for r in rows:
            w.writerow({"instance": "numpy", "gatebase": "ct", "merged": "True", "eps_rot": "", "eps_synth": "", **r})


def test_load_and_stats(tmp_path):
    row = lambda n, t, src="measured", **kw: {"scheme": "suzuki4", "n": n, "r": 10, "r_source": src, "t_total": t, **kw}
    _run(tmp_path / "seed1", [row(4, 100), row(13, 1000, "fit"), row(4, 999, gatebase="cz"), row(4, 999, merged="False")])
    _run(tmp_path / "seed2", [row(4, 300), row(13, 3000, "fit")])
    rows = pftcount.load_ct([tmp_path / "seed1", tmp_path / "seed2"])
    st = pftcount.series_stats(rows, "suzuki4", "measured", [1, 2])
    assert st == {4: {"mean": 200.0, "min": 100, "max": 300, "mean_r": 10.0}}
    assert pftcount.series_stats(rows, "suzuki4", "fit", [1, 2])[13]["mean"] == 2000.0
    with pytest.raises(ValueError, match="no row for seeds"):
        pftcount.series_stats(rows, "suzuki4", "measured", [1, 2, 3])


def test_tcount_figure_fits_series_model():
    st = lambda m: {"mean": m, "min": m * 0.9, "max": m * 1.1, "mean_r": 1}
    stats = {"suzuki4": {"measured": {4: st(1e5), 10: st(1e6)}, "fit": {13: st(2e6), 20: st(5e6)}},
             "mo-q6": {"measured": {4: st(7e4), 10: st(7e5)}, "fit": {13: st(1.4e6), 20: st(3e6)}}}
    tex = pftcount.tcount_figure_tex(stats, ["suzuki4", "mo-q6"], ["Generated by pysimcount.pftcount -- test"])
    series, guides = figdrop.parse_series(tex)
    assert [s.legend for s in series] == ["Suzuki S4", "M\\&O q=6 (rec., Tab. 2)"] and guides == 0
    assert all(len(s.spans) == 2 for s in series)  # measured + fitted continuation
    assert "mark indices={2,3}" in tex and "dashed, mark=square*" in tex and "solid, mark=*" in tex
