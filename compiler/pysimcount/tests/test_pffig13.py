"""Tests for the Childs et al. Fig. 13 replica (pysimcount.pffig13)."""

import warnings

import pytest

warnings.filterwarnings("ignore")

from pysimcount import bounds, figdrop, pffig13  # noqa: E402
from pysimcount.nam import samples  # noqa: E402

N = 13


@pytest.fixture(scope="module")
def s2():
    return pffig13.run_case(2, N, seed=1, verify_max_n=N)


def test_s2_counts_by_hand(s2):
    # Unmerged S2 step: forward and reverse sweeps over XX, YY, ZZ on the n
    # periodic bonds, 2 CNOTs per two-qubit exponential -> 2 * 3n * 2 = 12n.
    assert s2["before_per_step"]["CNOT"] == 12 * N
    # In a chain, the ZZ pair in the middle of each step (the fields between
    # them are diagonal and commute) and the XX pair at each step boundary
    # merge: 2 * 2n CNOTs fewer per step -> 8n.
    assert s2["marginal_per_step"]["CNOT"] == 8 * N
    # r is Childs et al. Eq. 147: ceil(39.4696 * 13^1.88264) = 4937.
    assert s2["r"] == 4937 == bounds.empirical(2, _H(N), float(N), 1e-3)
    assert s2["before_total"]["CNOT"] == 12 * N * 4937
    assert s2["verified"] and s2["verify_state_err"] < 1e-9


def _H(n):
    from pysimcount.pfcompare import heisenberg, numpy_fields
    return heisenberg(n, numpy_fields(n, 1))


def test_first_order_has_no_cnot_saving():
    # Childs et al. SI I.3: "The first-order PF circuits do not admit any
    # optimization in the cnot counts."
    c = pffig13.run_case(1, N, seed=1, verify_max_n=0)
    assert c["marginal_per_step"]["CNOT"] == c["before_per_step"]["CNOT"] == 6 * N
    assert not c["verified"]


def test_counts_do_not_depend_on_fields():
    a = pffig13.run_case(2, N, seed=1, verify_max_n=0)
    b = pffig13.run_case(2, N, seed=2, verify_max_n=0)
    assert a["fields"] != b["fields"]
    for k in ("r", "before_per_step", "marginal_per_step", "edge"):
        assert a[k] == b[k], k


@pytest.mark.skipif(not samples.path_for("pf4emp", N, "preoptim").exists(), reason="simcount samples not on disk")
def test_s4_matches_published_circuits():
    c = pffig13.run_case(4, N, seed=1, verify_max_n=0)
    # Published pf4emp n=13 pre-optimisation circuit: 780 CNOT per step x r = 218.
    assert c["published"]["before"]["CNOT"] == c["before_total"]["CNOT"] == 780 * 218
    # Their optimised circuit has 113,386 CNOTs; ours r x 520 + edge.
    assert c["marginal_per_step"]["CNOT"] == 520
    assert c["published"]["after"]["CNOT"] == 113_386


def test_figure_fits_the_figdrop_series_model(s2):
    case4 = dict(s2, order=4)
    tex = pffig13.figure_tex([s2, case4], ["Generated by pysimcount.pffig13 -- test"])
    series, guides = figdrop.parse_series(tex)
    assert [s.legend for s in series] == ["Second order", "Fourth order"] and guides == 0
    assert len(series[0].spans) == 2  # after (legend) + before (forget plot)
