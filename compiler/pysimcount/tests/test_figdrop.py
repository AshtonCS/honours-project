"""figdrop removes exactly one formula's series and measures its share of the y-axis."""

import pytest

from pysimcount import figdrop

# S1 at 1e5..1e6 (measured) plus an extrapolated continuation to 1e6; S2 at 1e2..1e3.
# log y-range with S1: log10(1e6 / 1e2) = 4 decades; without: log10(1e3 / 1e2) = 1.
# share = (4 - 1) / 4 = 0.75.
TEX = r"""% Generated by pysimcount.pffigure -- do not edit; regenerate instead.
% figure: X -- test
\begin{tikzpicture}
  \begin{loglogaxis}[]
    \addplot[only marks, red, mark=*] coordinates {
      (4,100000)
    };
    \addlegendentry{Lie-Trotter S1}
    \addplot[only marks, red, mark=*, forget plot] coordinates {
      (13,1000000)
    };
    \addplot[only marks, red, mark=triangle*] coordinates {
      (4,100) += (0,900) -= (0,0)
    };
    \addlegendentry{Suzuki S2}
    \addlegendimage{only marks, black, mark=*}
    \addlegendentry{measured $r$}
  \end{loglogaxis}
\end{tikzpicture}
"""

S2_ONLY = r"""% Generated by pysimcount.pffigure -- do not edit; regenerate instead.
% figure: X -- test
\begin{tikzpicture}
  \begin{loglogaxis}[]
    \addplot[only marks, red, mark=triangle*] coordinates {
      (4,100) += (0,900) -= (0,0)
    };
    \addlegendentry{Suzuki S2}
    \addlegendimage{only marks, black, mark=*}
    \addlegendentry{measured $r$}
  \end{loglogaxis}
\end{tikzpicture}
"""


def test_series_include_forget_plot_continuation_and_error_bar_ends():
    series, guides = figdrop.parse_series(TEX)
    assert guides == 0
    assert [s.legend for s in series] == ["Lie-Trotter S1", "Suzuki S2"]
    assert max(series[0].ys) == 1e6 and max(series[1].ys) == 1000  # 100 + 900 error bar


def test_share_by_hand():
    series, _ = figdrop.parse_series(TEX)
    assert figdrop.share(series, "Lie-Trotter S1") == pytest.approx(0.75)


def test_drop_removes_series_and_continuation_only():
    out, gone = figdrop.drop(TEX, "Lie-Trotter S1")
    assert gone == ["Lie-Trotter S1"]
    assert out == S2_ONLY


def test_drop_refuses_when_nothing_would_remain_or_name_absent():
    with pytest.raises(ValueError, match="nothing would remain"):
        figdrop.drop(S2_ONLY, "Suzuki S2")
    with pytest.raises(ValueError, match="no series"):
        figdrop.drop(S2_ONLY, "Lie-Trotter S1")


def test_drop_refuses_with_expression_guides():
    guided = TEX.replace(r"    \addlegendimage", "    \\addplot[black, dotted] {x^2};\n    \\addlegendentry{slope}\n"
                         r"    \addlegendimage", 1)
    assert figdrop.parse_series(guided)[1] == 1
    with pytest.raises(ValueError, match="expression plot"):
        figdrop.drop(guided, "Lie-Trotter S1")


def test_derived_text_keeps_header_and_names_source(tmp_path):
    src = tmp_path / "A.tex"
    src.write_text(TEX)
    out = figdrop.derived_text(src, "Lie-Trotter S1", 0.75)
    lines = out.splitlines()
    assert lines[:2] == TEX.splitlines()[:2]
    assert lines[2].startswith("% derived: A.tex with Lie-Trotter S1 removed") and "75%" in lines[2]
    assert figdrop.is_derived(out) and not figdrop.is_derived(TEX)


def test_fixed_y_axis_is_detected():
    assert figdrop.has_fixed_y("  \\begin{loglogaxis}[\n    ymin=30000, ymax=5e+10,\n  ]")
    assert figdrop.has_fixed_y("\\begin{axis}[xmin=1, ymax=10]")
    assert not figdrop.has_fixed_y("\\begin{loglogaxis}[\n    xmin=10, xmax=110,\n    ymajorgrids=true, yminorgrids=true,\n  ]")
    assert not figdrop.has_fixed_y("% header mentions ymin=3\n\\begin{axis}[xmin=1]")
