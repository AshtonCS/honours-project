def test_derived_copy_names_its_original_and_hides_it(tmp_path):
    d = tmp_path / "np-main" / "f"
    d.mkdir(parents=True)
    (d / "A-measured-by-order.tex").write_text(TEX)
    copy = TEX.replace("% seed 1:", "% derived: A-measured-by-order.tex with Suzuki S4 removed by pysimcount.figdrop "
                       "(x); source_sha256=0\n% seed 1:")
    (d / "A-measured-by-order-no-suzuki4.tex").write_text(copy)
    recs = [figgallery.describe(p, tmp_path, NAMES) for p in sorted(d.iterdir())]
    figgallery.link_derived(recs)
    der, orig = sorted(recs, key=lambda r: not r["derived_from"])
    assert der["derived_from"] == "np-main/f/A-measured-by-order.tex"
    assert der["title"].endswith("(without Suzuki S4)")
    assert orig["replaced_by"] == "np-main/f/A-measured-by-order-no-suzuki4.tex"


def test_explicit_r_method_in_header_wins(tmp_path):
    from pysimcount import figgallery
    from pysimcount.pfcompare import formula_registry
    names = {k: f.name for k, f in formula_registry().items()}
    d = tmp_path / "exp" / "figures"
    d.mkdir(parents=True)
    f = d / "fig.tex"
    f.write_text("% Generated by pysimcount.pffig13 -- test\n% figure: fig -- a title\n"
                 "% metric=cnot gatebase=cz unmerged; r_method=emp: r = Eq. 147, not our measured r\n"
                 "% formulas: Suzuki S4, Suzuki S6\n"
                 "\\begin{tikzpicture}\n\\addplot coordinates {(1,1)};\n\\addlegendentry{Fourth order}\n\\end{tikzpicture}\n")
    rec = figgallery.describe(f, tmp_path, names)
    assert rec["r_method"] == "empirical fit (2018, Eq. 147)"
    assert rec["formulas"] == "suzuki4;suzuki6"


def _main_cfg(items):
    return {"sections": {"RQ1": "q1"}, "items": items}


def test_load_main_tags_figures_and_checks_tables(tmp_path):
    import json
    (tmp_path / "t.md").write_text("| a |")
    recs = [_rec(path="a/F.tex"), _rec(path="a/G.tex")]
    p = tmp_path / "main.json"
    p.write_text(json.dumps(_main_cfg([
        {"section": "RQ1", "label": "F1", "kind": "figure", "status": "ready", "path": "a/F.tex", "role": "r"},
        {"section": "RQ1", "label": "T1", "kind": "table", "status": "update", "path": "t.md", "role": "r", "todo": "x"},
        {"section": "RQ1", "label": "T2", "kind": "missing", "status": "missing", "make": "m", "role": "r"}])))
    figgallery.load_main(p, recs, tmp_path)
    assert [r["main_body"] for r in recs] == ["RQ1 F1", ""]


def test_load_main_rejects_bad_items(tmp_path):
    import json
    import pytest
    recs = [_rec(path="a/F.tex"), _rec(path="a/H.tex", replaced_by="a/H-no-lie-trotter.tex")]
    base = {"section": "RQ1", "label": "F1", "kind": "figure", "status": "ready", "path": "a/F.tex", "role": "r"}
    for bad, msg in [({"section": "RQ9"}, "unknown section"), ({"status": "done"}, "status one of"),
                     ({"path": "a/X.tex"}, "not a figure"), ({"path": "a/H.tex"}, "select that"),
                     ({"kind": "table", "path": "nope.md"}, "does not exist"),
                     ({"kind": "missing", "status": "missing"}, "'make' note"),
                     ({"kind": "missing"}, "both be 'missing'")]:
        p = tmp_path / "main.json"
        p.write_text(json.dumps(_main_cfg([{**base, **bad}])))
        with pytest.raises(ValueError, match=msg):
            figgallery.load_main(p, recs, tmp_path)


