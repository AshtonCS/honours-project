"""figgallery reads attributes only from what a figure file states."""

from pysimcount import figgallery

TEX = r"""% Generated by pysimcount.pfseeds -- do not edit; regenerate instead.
% figure: A-measured-by-order -- Suzuki formulas of each order, r from: Measured $r$; median over seeds [1, 2], bars = min..max
% metric=total gatebase=cz merged
% seed 1: git_commit=0123456789abcdef git_dirty=False
\begin{tikzpicture}
  \begin{loglogaxis}[]
    \addplot coordinates {(4,1)};
    \addlegendentry{Suzuki S4}
    \addplot coordinates {(4,2)};
    \addlegendentry{M\&O q=6 (rec., Tab. 2)}
    \addlegendimage{only marks}
    \addlegendentry{fitted $r$ (extrapolated)}
  \end{loglogaxis}
\end{tikzpicture}
"""

NAMES = {"suzuki4": "Suzuki S4", "mo-q6": "M&O q=6 (rec., Tab. 2)", "suzuki2": "Suzuki S2"}


def test_describe_reads_header_path_and_legend(tmp_path):
    p = tmp_path / "np-main" / "aggregate" / "figures" / "merged" / "total" / "A-measured-by-order.tex"
    p.parent.mkdir(parents=True)
    p.write_text(TEX)
    assert figgallery.is_figure(p)
    rec = figgallery.describe(p, tmp_path, NAMES)
    assert rec["experiment"] == "np-main"
    assert rec["generator"] == "pysimcount.pfseeds"
    assert rec["scope"] == "aggregate over seeds"
    assert rec["seeds"] == "[1, 2]"
    assert (rec["metric"], rec["gate_set"], rec["merged"]) == ("total", "cz", "merged")
    assert rec["statistic"] == "median over seeds"
    assert rec["r_method"] == "measured"
    assert rec["extrapolated"] == "yes"
    assert rec["formulas"] == "suzuki4;mo-q6"
    assert rec["git_commit"] == "0123456"


def test_documents_and_wrappers_are_not_figures(tmp_path):
    doc = tmp_path / "all.tex"
    doc.write_text("\\documentclass{article}\\begin{document}\\begin{tikzpicture}\\end{tikzpicture}\\end{document}")
    assert not figgallery.is_figure(doc)
    other = tmp_path / "notes.tex"
    other.write_text("\\section{x}")
    assert not figgallery.is_figure(other)


RQ_CFG = {"questions": {"RQ1": "q1", "RQ2": "q2"},
          "rules": [{"rq": ["RQ1"], "tier": "related", "match": {"experiment": "np-*"}, "reason": "broad"},
                    {"rq": ["RQ1"], "tier": "key", "match": {"metric": ["cnot", "t"]}, "reason": "narrow"},
                    {"rq": ["RQ2"], "tier": "related", "match": {"path": "np-main/*C-*"}, "reason": "bounds"}]}


def _rec(**kw):
    rec = {c: "" for c in figgallery.COLUMNS}
    rec.update(kw)
    return rec


def test_assign_rq_keeps_highest_tier_and_every_reason():
    recs = [_rec(experiment="np-main", metric="cnot", path="np-main/x/C-s4.tex"),
            _rec(experiment="np-main", metric="total", path="np-main/x/B.tex"),
            _rec(experiment="pf-thesis", metric="t", path="pf-thesis/B.tex")]
    figgallery.assign_rq(recs, RQ_CFG)
    assert [(r["rq_key"], r["rq_related"]) for r in recs] == [("RQ1", "RQ2"), ("", "RQ1"), ("RQ1", "")]
    assert recs[0]["rq_reasons"] == "RQ1 related: broad | RQ1 key: narrow | RQ2 related: bounds"


def test_assign_rq_rejects_a_rule_matching_nothing():
    import pytest
    with pytest.raises(ValueError, match="matches no figure"):
        figgallery.assign_rq([_rec(experiment="pf-x", metric="total")], RQ_CFG)


def test_load_rq_rejects_unknown_field_tier_or_rq(tmp_path):
    import json
    import pytest
    for bad, msg in [({"match": {"colour": "x"}}, "unknown manifest field"), ({"tier": "core"}, "tier"),
                     ({"rq": ["RQ9"]}, "unknown RQ")]:
        rule = {**RQ_CFG["rules"][0], **bad}
        p = tmp_path / "rq.json"
        p.write_text(json.dumps({"questions": RQ_CFG["questions"], "rules": [rule]}))
        with pytest.raises(ValueError, match=msg):
            figgallery.load_rq(p)


