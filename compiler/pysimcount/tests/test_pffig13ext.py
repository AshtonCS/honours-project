"""Tests for the extended Fig. 13 (pysimcount.pffig13ext)."""

import csv
import warnings

import pytest

warnings.filterwarnings("ignore")

from pysimcount import figdrop, pffig13, pffig13ext  # noqa: E402

N = 13


@pytest.mark.parametrize("scheme,order", [("lie-trotter", 1), ("suzuki4", 4)])
def test_suzuki_step_is_the_replica_step(scheme, order):
    # At the replica's r (Eq. 147), the extension's step for a Suzuki formula
    # must be the same circuit as the replica's, so the two figures differ
    # only through r.
    rep = pffig13.run_case(order, N, seed=1, verify_max_n=0)
    ext = pffig13ext.run_case(scheme, N, rep["r"], seed=1, verify_max_n=0)
    for k in ("before_per_step", "marginal_per_step", "edge", "before_total", "after_total"):
        assert ext[k] == rep[k], k
    assert ext["r_eq147"] == rep["r"]


def test_new_formula_verified_and_field_independent():
    a = pffig13ext.run_case("mo-q6", N, 300, seed=1, verify_max_n=N)
    b = pffig13ext.run_case("mo-q6", N, 300, seed=2, verify_max_n=0)
    assert a["verified"] and a["verify_state_err"] < 1e-9
    assert "r_eq147" not in a
    for k in ("before_per_step", "marginal_per_step", "edge"):
        assert a[k] == b[k], k
    # Optimisation never adds CNOTs, and after = r x marginal + edge.
    assert a["marginal_per_step"]["CNOT"] <= a["before_per_step"]["CNOT"]
    assert a["after_total"]["CNOT"] == 300 * a["marginal_per_step"]["CNOT"] + a["edge"]["CNOT"]


def _write_run(d, rows):
    d.mkdir(parents=True)
    with open(d / "results.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["scheme", "n", "r", "r_source", "gatebase"])
        w.writeheader()
        w.writerows(rows)


def test_mean_measured_r(tmp_path):
    row = lambda n, r, src="measured", gb="cz": {"scheme": "suzuki4", "n": n, "r": r, "r_source": src, "gatebase": gb}
    _write_run(tmp_path / "a" / "seed1", [row(5, 10), row(6, 20), row(5, 999, "fit"), row(5, 999, gb="ct")])
    _write_run(tmp_path / "a" / "seed2", [row(5, 14), row(6, 30)])
    dirs = [tmp_path / "a" / "seed1", tmp_path / "a" / "seed2"]
    assert pffig13ext.mean_measured_r(dirs, ["suzuki4"], [5, 6], [1, 2]) == {"suzuki4": {5: 12.0, 6: 25.0}}
    with pytest.raises(ValueError, match="no measured r"):
        pffig13ext.mean_measured_r(dirs, ["suzuki4"], [5, 6, 7], [1, 2])
    _write_run(tmp_path / "b" / "seed1", [row(5, 11)])
    with pytest.raises(ValueError, match="conflicting"):
        pffig13ext.mean_measured_r(dirs + [tmp_path / "b" / "seed1"], ["suzuki4"], [5], [1, 2])


def test_figure_and_y_range():
    c = pffig13ext.run_case("suzuki2", N, 4937, seed=1, verify_max_n=0)  # Eq. 147 r
    d = pffig13ext.run_case("mo-q6", N, 300, seed=1, verify_max_n=0)
    tex = pffig13ext.figure_tex([c, d], ["suzuki2", "mo-q6"], ["Generated by pysimcount.pffig13ext -- test"])
    series, guides = figdrop.parse_series(tex)
    assert [s.legend for s in series] == ["Suzuki S2", "M\\&O q=6 (rec., Tab. 2)"] and guides == 0
    assert pffig13ext.y_range([c], "CNOT") == pffig13.YRANGE["CNOT"]
    big = dict(c, before_total={"CNOT": 7e10}, after_total={"CNOT": 1e4})
    assert pffig13ext.y_range([big], "CNOT") == (1e4, 1e11)


def test_line_variant_fits_series_model_and_autoscales():
    c = pffig13ext.run_case("suzuki6", N, 52, seed=1, verify_max_n=0)
    d = pffig13ext.run_case("mo-q14", N, 40, seed=1, verify_max_n=0)
    tex = pffig13ext.figure_tex([c, d], ["suzuki6", "mo-q14"], ["Generated by pysimcount.pffig13ext -- test"],
                                lines=True)
    series, guides = figdrop.parse_series(tex)
    assert [s.legend for s in series] == ["Suzuki S6", "M\\&O q=14 (rec., Tab. 3)"] and guides == 0
    assert not figdrop.has_fixed_y(tex)
    # colour and marker per formula as in np-childs-format: after solid + filled, before dashed + open
    assert tex.count(", solid, mark=") == 2 and tex.count(", dashed, mark=") == 2
    from pysimcount.pfchilds import _style
    from pysimcount.pfcompare import formula_registry
    for k in ("suzuki6", "mo-q14"):
        _, colour, mark = _style(k, formula_registry())
        assert f"\\addplot[{colour}, solid, mark={mark}," in tex and f"\\addplot[{colour}, dashed, mark={mark}," in tex


@pytest.mark.parametrize("show,mark,key", [("before", "diamond*", "before_total"), ("after", "*", "after_total")])
def test_single_series_line_variants(show, mark, key):
    c = pffig13ext.run_case("mo-q14", N, 40, seed=1, verify_max_n=0)
    tex = pffig13ext.figure_tex([c], ["mo-q14"], ["Generated by pysimcount.pffig13ext -- test"], lines=True, show=show)
    series, _ = figdrop.parse_series(tex)
    assert len(series) == 1 and len(series[0].spans) == 1
    assert f"mark={mark}," in tex and "forget plot" not in tex and "addlegendimage" not in tex
    assert series[0].ys[0] == c[key]["CNOT"]
    with pytest.raises(ValueError):
        pffig13ext.figure_tex([c], ["mo-q14"], [], show=show)  # single-series needs lines=True
