"""figuniform draws extrapolated points in their series' measured style and touches nothing else."""

import pytest

from pysimcount import figuniform

# pfseeds-style figure: S4 measured at n = 8, 10, open-marker fit at 13 (and the
# joining point 10, which is measured, not extrapolated), plus the two style keys.
TEX = r"""% Generated by pysimcount.pfseeds -- do not edit; regenerate instead.
% figure: X -- test
\begin{tikzpicture}
  \begin{loglogaxis}[]
    \addplot[red, solid, mark=square*, mark options={solid, fill=red}] coordinates {
      (8,100)
      (10,200)
    };
    \addlegendentry{Suzuki S4}
    \addplot[red, dashed, mark=square*, mark options={solid, fill=white}, forget plot] coordinates {
      (10,200)
      (13,400)
    };
    \addlegendimage{only marks, black, mark=*}
    \addlegendentry{measured $r$}
    \addlegendimage{only marks, black, mark=*, mark options={fill=white}}
    \addlegendentry{fitted $r$ (extrapolated)}
  \end{loglogaxis}
\end{tikzpicture}
"""

# pfgroupfigure-style: open markers mean the two-group grouping, not a fit.
GROUPING = r"""% Generated by pysimcount.pfgroupfigure -- do not edit; regenerate instead.
\begin{tikzpicture}
  \begin{loglogaxis}[]
    \addplot[red, solid, mark=*, mark options={solid, fill=red}] coordinates {
      (4,10)
    };
    \addlegendentry{Suzuki S2}
    \addplot[red, dashed, mark=*, mark options={solid, fill=white}, forget plot] coordinates {
      (4,8)
    };
    \addlegendimage{black, dashed, mark=*, mark options={solid, fill=white}}
    \addlegendentry{two-group ($E'$ outer)}
  \end{loglogaxis}
\end{tikzpicture}
"""


def test_continuation_takes_series_style_and_keys_go():
    new, ns = figuniform.restyle(TEX)
    assert ns == [13]  # 10 is plotted by the measured series too
    assert r"\addplot[red, solid, mark=square*, mark options={solid, fill=red}, forget plot] coordinates {" in new
    assert "fill=white" not in new and "dashed" not in new
    assert "measured $r$" not in new and "fitted $r$" not in new
    # data and every other line unchanged
    assert new.count("(10,200)") == 2 and "(13,400)" in new
    kept = [l for l in TEX.splitlines() if "addplot[red, dashed" not in l and "addlegendimage" not in l
            and "measured $r$" not in l and "fitted $r$" not in l]
    assert new.splitlines() == kept[:9] + [new.splitlines()[9]] + kept[9:]


def test_scope_needs_the_figure_to_say_open_means_fitted():
    assert figuniform.in_scope(TEX)
    assert not figuniform.in_scope(GROUPING)
    header = GROUPING.replace("% Generated", "% open markers: r from each seed's power-law fit\n% Generated")
    assert figuniform.in_scope(header)


def test_divider_and_its_label_are_removed():
    tex = TEX.replace(r"  \end{loglogaxis}",
                      "    \\draw[gray, densely dashed] (axis cs:11.4,1) -- (axis cs:11.4,1000);\n"
                      "    \\node[gray, font=\\scriptsize, anchor=north west] at (axis cs:11.4,1000) {fitted $r$};\n"
                      "  \\end{loglogaxis}")
    new, _ = figuniform.restyle(tex)
    assert "\\draw" not in new and "\\node" not in new


def test_open_series_without_measured_style_raises():
    tex = TEX.replace("mark options={solid, fill=red}]", "mark options={solid, fill=white}]")
    with pytest.raises(ValueError, match="no measured style"):
        figuniform.restyle(tex)


def test_forget_plot_goes_before_error_bar_keys():
    # after "error bars/.cd", pgfplots reads keys as error-bar keys and rejects forget plot
    tex = TEX.replace("fill=red}]", "fill=red}, error bars/.cd, y explicit]").replace(
        "fill=white}, forget plot]", "fill=white}, forget plot, error bars/.cd, y explicit]")
    new, _ = figuniform.restyle(tex)
    assert "fill=red}, forget plot, error bars/.cd, y explicit] coordinates {" in new


def test_error_bar_mismatch_raises():
    tex = TEX.replace("fill=white}, forget plot]", "fill=white}, forget plot, error bars/.cd, y explicit]")
    with pytest.raises(ValueError, match="error bars"):
        figuniform.restyle(tex)


def test_derived_line_names_source_and_extrapolated_n(tmp_path):
    src = tmp_path / "X.tex"
    src.write_text(TEX)
    out = figuniform.derived_text(src)
    head = [l for l in out.splitlines() if l.startswith("%")]
    assert head[:2] == TEX.splitlines()[:2]
    assert head[2].startswith("% derived: X.tex restyled by pysimcount.figuniform")
    assert "extrapolated n = [13]" in head[2] and "source_sha256=" in head[2]
