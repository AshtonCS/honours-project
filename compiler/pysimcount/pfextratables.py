"""Main-body tables that had no generator: fitted exponents (RQ3), cheapest Suzuki formula
under each source of r (RQ2), and the simcount parity summary (Validation).

    python -m pysimcount.pfextratables results/np-mean/extra-tables.json [--only <table>]

exponents       From a pfchilds record (the n = 5-11 fit): per formula the exponent b
                of the mean-r fit r = a n^b, the min-max of the per-seed fits' b, the
                bound scaling 1 + 2/p (Childs et al. 2021, Sec. 4.1, r ~ n^(1/p)
                t^(1+1/p), with t = n -- the substitution is ours), and for Suzuki
                orders the exponent of Childs et al. 2018 Eq. 147 as hard-coded in
                simcount (``bounds._EMPIRICAL``).
bound-winners   For every source of r in the runs (measured; bounds tte, com, min,
                ana; the empirical fit emp) and every measured n: on each seed the
                Suzuki formula with the lowest merged CNOT total (cz) among those
                with a value under that source (tte and com exist for orders 1, 2,
                4 only), and the number of seeds on which it wins. Ties are broken
                by formula id, as in ``pfseeds.win_counts``.
parity          Replays every cached simcount fixture with the same comparison as
                ``tests/test_simcount_parity.py`` (r, total per-step gates, every
                aggregated gate count matched by label) and tabulates matched cases
                per formula and bound; Clifford+T fixtures need the Quipper backend
                and are listed as not checked.

bound-ratios    LaTeX/Markdown cut of ``pfboundratio``'s results.json at one n: bound r /
                measured r per Suzuki order and bound (geometric mean, min-max over
                seeds), the main-body version of np-bounds-ratio/table.md.
grouping        LaTeX/Markdown cut of ``pfmean``'s summary.json at one n, variant and
                metric: X-Y-Z / two-group gain = step ratio x r ratio per formula
                (geometric mean, min-max, seeds where two-group is cheaper).

Each table is written as ``<out>.md``, ``<out>.tex`` and ``<out>.json`` beside the config.
"""

from __future__ import annotations

import argparse
import json
import re
import warnings
from collections import Counter, defaultdict
from pathlib import Path

from . import bounds, pfchilds, pffigure
from .pfcompare import formula_registry, provenance

SOURCES = ("measured", "tte", "emp", "com", "min", "ana")
SOURCE_NAMES = {"measured": "measured $r$", "tte": "commutator bound (2021)", "emp": "empirical fit (2018)",
                "com": "commutator bound (2018)", "min": "minimised bound", "ana": "analytic bound"}
SUZUKI = ("lie-trotter", "suzuki2", "suzuki4", "suzuki6", "suzuki8")
SHORT = {"lie-trotter": "S1", "suzuki2": "S2", "suzuki4": "S4", "suzuki6": "S6", "suzuki8": "S8"}


def _write(here: Path, out: str, md: str, tex: str, data: dict, generator: str) -> None:
    prov = provenance()
    stamp = f"git_commit={prov['git_commit']} git_dirty={prov['git_dirty']}"
    p = here / out
    p.with_suffix(".md").write_text(md.replace("{stamp}", stamp))
    p.with_suffix(".tex").write_text(f"% Generated by pysimcount.pfextratables ({generator}); {stamp}; "
                                     "do not edit, regenerate instead.\n" + tex)
    p.with_suffix(".json").write_text(json.dumps({**data, "provenance": prov}, indent=1))
    print(f"  wrote {p.with_suffix('.md')}, .tex, .json")


# ------------------------------------------------------------------ exponents

def exponents(rec: dict) -> list[dict]:
    registry = formula_registry()
    rows = []
    for k, s in rec["series"].items():
        p = registry[k].order
        bs = [b for _, b in s["per_seed_fit"].values()]
        rows.append({"scheme": k, "order": p, "b": s["fit"]["b"], "b_min": min(bs), "b_max": max(bs),
                     "theory": 1 + 2 / p,
                     "eq147": bounds._EMPIRICAL[p][1] if registry[k].family == "suzuki" else None})
    return sorted(rows, key=lambda r: (r["order"], r["scheme"] not in SUZUKI, r["scheme"]))


def exponents_tables(rows: list[dict], rec: dict, names: dict[str, str]) -> tuple[str, str]:
    fit = rec["fit_sizes"]
    md = ["# Fitted exponent b of r = a n^b (RQ3)", "",
          f"From `{rec['id']}.json`: mean measured r over seeds {rec['seeds']} fitted on n = {fit[0]}-{fit[-1]} "
          "(least squares in log-log); per-seed range = the same fit on each seed alone. Theory 1 + 2/p: Childs et al. "
          "2021 Sec. 4.1 with t = n (our substitution). Eq. 147: Childs et al. 2018 (simcount's constants), Suzuki "
          "only. Made at {stamp}.", "",
          "| formula | p | b (mean r) | per-seed b (min–max) | 1 + 2/p | Eq. 147 |", "|---|---:|---:|---:|---:|---:|"]
    tex = [f"% fitted exponent b of r = a n^b, fit on n = {fit[0]}--{fit[-1]}, mean r over seeds {rec['seeds']}",
           "\\begin{tabular}{lrrrrr}", "\\hline",
           "Formula & $p$ & $b$ (mean $r$) & per-seed $b$ & $1 + 2/p$ & Eq.~147 \\\\", "\\hline"]
    for r in rows:
        eq = f"{r['eq147']:.3f}" if r["eq147"] is not None else "--"
        md.append(f"| {names[r['scheme']]} | {r['order']} | {r['b']:.3f} | {r['b_min']:.3f}–{r['b_max']:.3f} | "
                  f"{r['theory']:.3f} | {eq if eq != '--' else '—'} |")
        tex.append(f"{pffigure.latex_escape(names[r['scheme']])} & {r['order']} & {r['b']:.3f} & "
                   f"{r['b_min']:.3f}--{r['b_max']:.3f} & {r['theory']:.3f} & {eq} \\\\")
    tex += ["\\hline", "\\end{tabular}", ""]
    return "\n".join(md) + "\n", "\n".join(tex)


# ------------------------------------------------------------------ bound winners

def bound_winners(runs: dict[int, dict], sizes: list[int]) -> list[dict]:
    """[{source, n, wins: {scheme: seeds}, candidates}] over every source and n with data."""
    seeds = sorted(runs)
    cnot: dict[int, dict[tuple[str, int, str], int]] = {}
    for s, run in runs.items():
        inst = run["meta"]["config"].get("instances", "simcount")
        cnot[s] = {(row["scheme"], int(row["n"]), row["r_source"]): int(row["cnot_total"]) for row in run["rows"]
                   if row["instance"] == inst and row["gatebase"] == "cz" and row["merged"]
                   and row["scheme"] in SUZUKI and row["r_source"] in SOURCES}
    out = []
    for src in SOURCES:
        for n in sizes:
            cands = sorted({k for (k, nn, ss) in cnot[seeds[0]] if nn == n and ss == src}, key=SUZUKI.index)
            if not cands:
                continue
            wins: Counter = Counter()
            for s in seeds:
                vals = {k: cnot[s].get((k, n, src)) for k in cands}
                if any(v is None for v in vals.values()):
                    raise ValueError(f"seed {s} lacks {src} rows at n={n} for {[k for k, v in vals.items() if v is None]}")
                wins[min(vals, key=lambda k: (vals[k], k))] += 1
            out.append({"source": src, "n": n, "candidates": cands, "wins": dict(wins)})
    return out


def _cell(wins: dict[str, int], n_seeds: int) -> tuple[str, str]:
    order = sorted(wins, key=lambda k: -wins[k])
    md = ", ".join(SHORT[k] + ("" if wins[k] == n_seeds else f" ({wins[k]})") for k in order)
    tex = ", ".join((SHORT[k] if k == "suzuki4" else f"\\textbf{{{SHORT[k]}}}")
                    + ("" if wins[k] == n_seeds else f" ({wins[k]})") for k in order)
    return md, tex


def bound_winners_tables(rows: list[dict], sizes: list[int], seeds: list[int]) -> tuple[str, str]:
    by = {(r["source"], r["n"]): r for r in rows}
    md = ["# Cheapest Suzuki formula under each source of r (RQ2)", "",
          f"Merged CNOT total (cz, eps = 1e-3, t = n), seeds {seeds}. Each cell: the formula cheapest on every seed, or "
          "each winner with its number of seeds. Candidates: the Suzuki orders with a value under that source (tte and "
          "com: orders 1, 2, 4 only; measured, emp, min, ana: 1-8). Made at {stamp}.", "",
          "| r from | " + " | ".join(f"n = {n}" for n in sizes) + " | candidates |",
          "|---|" + "---|" * len(sizes) + "---|"]
    tex = [f"% cheapest Suzuki formula by merged CNOT total under each source of r; seeds {seeds}; "
           "bold where it is not S4; (k) = seeds won when not all", "\\begin{tabular}{l" + "c" * len(sizes) + "}",
           "\\hline", "$r$ from & " + " & ".join(f"$n = {n}$" for n in sizes) + " \\\\", "\\hline"]
    for src in SOURCES:
        cells_md, cells_tex, cands = [], [], None
        for n in sizes:
            r = by.get((src, n))
            if r is None:
                cells_md.append("—"); cells_tex.append("--")
                continue
            m, t = _cell(r["wins"], len(seeds))
            cells_md.append(m); cells_tex.append(t)
            cands = cands or r["candidates"]
        if cands is None:
            continue
        md.append(f"| {src} | " + " | ".join(cells_md) + f" | {', '.join(SHORT[k] for k in cands)} |")
        tex.append(f"{SOURCE_NAMES[src]} & " + " & ".join(cells_tex) + " \\\\")
    tex += ["\\hline", "\\end{tabular}", ""]
    return "\n".join(md) + "\n", "\n".join(tex)


# ------------------------------------------------------------------ parity

_NAME = re.compile(r"n(\d+)_(pf\w+?)_(cz2ct|cz|ct)(?:_z(\d+))?_m(\d+)\.txt")


def parity() -> list[dict]:
    """One record per fixture: matched (bool) or 'not checked' for Clifford+T."""
    from . import compare, resources, simcount
    warnings.filterwarnings("ignore")
    out = []
    for path in sorted(simcount.FIXTURES.glob("*.txt")):
        m = _NAME.fullmatch(path.name)
        if not m:
            raise ValueError(f"unrecognised fixture name {path.name}")
        n, algo, g, z, seed = m.groups()
        n, seed, z = int(n), int(seed), (int(z) if z else None)
        rec = {"fixture": path.name, "n": n, "algo": algo, "gatebase": g, "seed": seed, "zrots": z}
        if g == "ct":
            out.append(rec | {"status": "not checked (needs --synth quipper)"})
            continue
        ref = simcount.run(n, algo, g, seed, z)
        pl = compare.run_pennylane(ref.hamiltonian, algo, g, zrots=z)
        ok = pl.sim.r == ref.r and resources.total(pl.step_counts) == resources.total(ref.per_step)
        for la, lb in compare._match_labels(ref.aggregated, pl.aggregated):
            ok = ok and la is not None and lb is not None and ref.aggregated[la] == pl.aggregated[lb]
        out.append(rec | {"status": "matched" if ok else "MISMATCH"})
    return out


def parity_tables(rows: list[dict]) -> tuple[str, str]:
    groups: dict[tuple[str, str], list[dict]] = defaultdict(list)
    for r in rows:
        groups[(r["algo"], r["gatebase"])].append(r)
    algo_re = re.compile(r"pf(\d)(\w+)")
    md = ["# Parity with simcount (Validation)", "",
          "Every cached simcount fixture replayed with the comparison of tests/test_simcount_parity.py: same r, same "
          "total per-step gates, every aggregated gate count equal (rotations matched by angle label). "
          "Made at {stamp}.", "",
          "| formula | r from | gate set | cases | sizes n | simcount seeds | matched |", "|---|---|---|---:|---|---|---:|"]
    tex = ["% simcount parity: cached fixtures replayed; matched = same r and every gate count",
           "\\begin{tabular}{lllrllr}", "\\hline",
           "Formula & $r$ from & gate set & cases & sizes $n$ & seeds & matched \\\\", "\\hline"]
    tot = Counter()
    for (algo, g), rs in sorted(groups.items(), key=lambda kv: (int(algo_re.match(kv[0][0]).group(1)), kv[0])):
        order, bound = algo_re.match(algo).groups()
        name = {"1": "Lie-Trotter S1"}.get(order, f"Suzuki S{order}")
        ns = sorted({r["n"] for r in rs}); ss = sorted({r["seed"] for r in rs})
        matched = sum(r["status"] == "matched" for r in rs)
        checked = sum(r["status"] in ("matched", "MISMATCH") for r in rs)
        tot["cases"] += len(rs); tot["matched"] += matched; tot["checked"] += checked
        mcell = (f"{matched}/{len(rs)}" if checked == len(rs) else "not checked (Clifford+T, needs Quipper)"
                 if checked == 0 else f"{matched}/{checked} checked; {len(rs) - checked} Clifford+T not checked")
        nrange = f"{ns[0]}–{ns[-1]}" if len(ns) > 1 else f"{ns[0]}"
        srange = f"{ss[0]}–{ss[-1]}" if len(ss) > 1 else f"{ss[0]}"
        md.append(f"| {name} | {bound} | {g} | {len(rs)} | {nrange} | {srange} | {mcell} |")
        tex.append(f"{name} & {bound} & {g} & {len(rs)} & {nrange.replace('–', '--')} & {srange.replace('–', '--')} & "
                   + (f"{matched}/{len(rs)}" if checked == len(rs) else "--$^*$") + " \\\\")
    md += ["", f"Total: {tot['cases']} fixtures; {tot['checked']} checked here, {tot['matched']} matched exactly; "
           f"{tot['cases'] - tot['checked']} Clifford+T fixtures need the Quipper backend."]
    tex += ["\\hline", f"Total & & & {tot['cases']} & & & {tot['matched']}/{tot['checked']}$^*$ \\\\", "\\hline",
            "\\multicolumn{7}{l}{\\footnotesize $^*$ Clifford+T fixtures need Ross's Quipper gridsynth and are not "
            "replayed here.} \\\\", "\\end{tabular}", ""]
    return "\n".join(md) + "\n", "\n".join(tex)


# ------------------------------------------------------------------ cuts of existing aggregates

def bound_ratio_tables(ratios: list[dict], n: int, names: dict[str, str], seeds_label: str) -> tuple[str, str, list]:
    rows = [r for r in ratios if r["n"] == n]
    if not rows:
        raise ValueError(f"no bound ratios at n={n}")
    by = {(r["scheme"], r["bound"]): r for r in rows}
    bounds_ = [b for b in ("tte", "com", "min", "ana", "emp") if any(k[1] == b for k in by)]
    schemes = [k for k in SUZUKI if any(kk[0] == k for kk in by)]
    head = {"tte": "commutator (2021)", "com": "commutator (2018)", "min": "minimised", "ana": "analytic",
            "emp": "empirical fit (2018)"}
    md = [f"# Bound r / measured r at n = {n} (RQ2)", "",
          f"From pfboundratio's results.json; geometric mean over seeds {seeds_label}, min–max in brackets; cz, eps = 1e-3, "
          "t = n. emp is a fit, not a bound. — = no such bound for that order. Made at {stamp}.", "",
          "| formula | " + " | ".join(head[b] for b in bounds_) + " |", "|---|" + "---:|" * len(bounds_)]
    tex = [f"% bound r / measured r at n = {n}; geometric mean over seeds {seeds_label}, min--max in brackets",
           "\\begin{tabular}{l" + "r" * len(bounds_) + "}", "\\hline",
           "Formula & " + " & ".join(head[b] for b in bounds_) + " \\\\", "\\hline"]
    fmt = lambda x: f"{x:,.0f}" if x >= 100 else f"{x:.2f}" if x < 10 else f"{x:.1f}"
    for k in schemes:
        cm, ct = [], []
        for b in bounds_:
            r = by.get((k, b))
            cm.append(f"{fmt(r['centre'])} ({fmt(r['min'])}–{fmt(r['max'])})" if r else "—")
            ct.append(f"{fmt(r['centre'])} ({fmt(r['min'])}--{fmt(r['max'])})" if r else "--")
        md.append(f"| {names[k]} | " + " | ".join(cm) + " |")
        tex.append(f"{pffigure.latex_escape(names[k])} & " + " & ".join(ct).replace(",", "{,}") + " \\\\")
    tex += ["\\hline", "\\end{tabular}", ""]
    return "\n".join(md) + "\n", "\n".join(tex), rows


def grouping_tables(recs: list[dict], n: int, variant: str, metric: str, names: dict[str, str],
                    order: list[str]) -> tuple[str, str, list]:
    rows = [g for g in recs if g["n"] == n and g["variant"] == variant and g["metric"] == metric]
    if not rows:
        raise ValueError(f"no grouping gains at n={n}, {variant}, {metric}")
    rows.sort(key=lambda g: order.index(g["scheme"]))
    md = [f"# X-Y-Z vs two-group at n = {n} ({variant}, {metric}) (RQ3)", "",
          "From pfmean's summary.json (np-grouping, 10 seeds, merged, measured r). gain = X-Y-Z / two-group = step ratio "
          "x r ratio (exact per seed, so also for geometric means); min–max over seeds. Made at {stamp}.", "",
          "| formula | step ratio | r ratio | gain (min–max) | seeds two-group cheaper |", "|---|---:|---:|---:|---:|"]
    tex = [f"% X-Y-Z / two-group at n = {n}, {variant}, {metric}; geometric mean over seeds, min--max in brackets",
           "\\begin{tabular}{lrrrr}", "\\hline",
           "Formula & step ratio & $r$ ratio & gain & two-group cheaper \\\\", "\\hline"]
    for g in rows:
        md.append(f"| {names[g['scheme']]} | {g['step_ratio']['centre']:.2f} | {g['r_ratio']['centre']:.2f} | "
                  f"{g['gain']['centre']:.2f} ({g['gain']['min']:.2f}–{g['gain']['max']:.2f}) | "
                  f"{g['seeds_two_group_cheaper']}/10 |")
        tex.append(f"{pffigure.latex_escape(names[g['scheme']])} & {g['step_ratio']['centre']:.2f} & "
                   f"{g['r_ratio']['centre']:.2f} & {g['gain']['centre']:.2f} ({g['gain']['min']:.2f}--"
                   f"{g['gain']['max']:.2f}) & {g['seeds_two_group_cheaper']}/10 \\\\")
    tex += ["\\hline", "\\end{tabular}", ""]
    return "\n".join(md) + "\n", "\n".join(tex), rows


# ------------------------------------------------------------------ main

def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("config", type=Path)
    ap.add_argument("--only", choices=["exponents", "bound-winners", "parity", "bound-ratios", "grouping"])
    args = ap.parse_args(argv)
    cfg = json.loads(args.config.read_text())
    here = args.config.parent
    for key in ("exponents", "bound-winners", "parity", "bound-ratios", "grouping"):
        if args.only and args.only != key:
            continue
        t = cfg[key]
        if (here / t["out"]).with_suffix(".json").resolve() == args.config.resolve():
            raise ValueError("an output would overwrite the config; choose another 'out'")
        registry = formula_registry()
        names = {k: registry[k].name for k in registry} | cfg.get("names", {})
        if key == "exponents":
            rec = json.loads((here / t["record"]).read_text())
            rows = exponents(rec)
            md, tex = exponents_tables(rows, rec, names)
            _write(here, t["out"], md, tex, {"record": t["record"], "rows": rows}, key)
        elif key == "bound-winners":
            runs = pfchilds.load_run_set(here, t["runs"])
            rows = bound_winners(runs, t["sizes"])
            md, tex = bound_winners_tables(rows, t["sizes"], sorted(runs))
            _write(here, t["out"], md, tex, {"seeds": sorted(runs), "sizes": t["sizes"], "rows": rows}, key)
        elif key == "bound-ratios":
            d = json.loads((here / t["source"]).read_text())
            seeds = sorted({int(s) for r in d["ratios"] for s in r["per_seed"]})
            md, tex, rows = bound_ratio_tables(d["ratios"], t["n"], names, str(seeds))
            _write(here, t["out"], md, tex, {"source": t["source"], "n": t["n"], "rows": rows}, key)
        elif key == "grouping":
            d = json.loads((here / t["source"]).read_text())
            md, tex, rows = grouping_tables(d["grouping_gains"], t["n"], t["variant"], t["metric"], names, list(registry))
            _write(here, t["out"], md, tex, {"source": t["source"], "n": t["n"], "variant": t["variant"],
                                             "metric": t["metric"], "rows": rows}, key)
        else:
            rows = parity()
            bad = [r["fixture"] for r in rows if r["status"] == "MISMATCH"]
            md, tex = parity_tables(rows)
            _write(here, t["out"], md, tex, {"rows": rows}, key)
            if bad:
                raise SystemExit(f"parity mismatches: {bad}")


if __name__ == "__main__":
    main()
