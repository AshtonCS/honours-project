"""Searchable index of every pgfplots figure under ``results/``.

    python -m pysimcount.figgallery results [--render] [--jobs 4]

Scans ``results/**/*.tex`` for figure files (a ``tikzpicture`` that is not a
LaTeX document: ``all.tex`` and render wrappers are skipped), and for each
records attributes read from the file itself -- its path, the generator's
header comments, and its legend -- plus the ``<id>.json`` sidecar that
``pfchilds`` writes, where present. Nothing is inferred that the file does
not state: an attribute the file does not carry is left blank.

Writes into ``results/gallery/``:

* ``manifest.csv`` and ``manifest.json``: one row per figure;
* ``index.html``: a static page (manifest embedded, no server or network
  needed) with a filter per attribute, a formula filter, free-text search and
  a research-question filter. Relevance to RQ1-RQ4 is not read from the
  figures: it comes from the hand-written rules in ``--rq`` (default
  ``results/gallery/rq-relevance.json``), which tag each figure 'key' or
  'related' per RQ. Key figures are shown in a section at the top;
* a proposed main-body selection (``--main``, default ``results/gallery/main-body.json``
  when present): figures, tables and not-yet-generated items per RQ with a status, shown
  first and outlined wherever they appear (``main_body`` column in the manifest);
* copies written by ``pysimcount.figdrop`` (``<stem>-no-<formula>.tex``,
  marked by a ``% derived:`` header line) replace their original on the page,
  with a link back; both stay in the manifest (``derived_from`` /
  ``replaced_by``) and a copy inherits its original's RQ tags. Run figdrop
  first to reproduce the page;
* with ``--render``: ``rendered/<slug>.pdf`` and ``.png`` per figure
  (``pfchilds.render_tex``), rebuilt only when the ``.tex`` is newer. A figure
  that fails to compile is listed with ``render_status`` = the error, not
  dropped.
"""

