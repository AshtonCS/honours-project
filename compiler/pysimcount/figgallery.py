# Legend entries that describe a marker or line style, not a formula.
STYLE_LEGENDS = ("measured", "fitted", "computed", "extrapolat", "slope", "grouping", "two-group", "optimised count",
                 "two groups", "x-y-z", "even/odd")
METHOD_NAMES = {"ana": "analytic bound", "min": "minimised bound", "com": "commutator bound (2018)",
                "emp": "empirical fit (2018, Eq. 147)", "tte": "commutator bound (2021)", "measured": "measured",
                "measured-fit": "measured + power-law fit (mean r)"}
COLUMNS = ["slug", "path", "experiment", "scope", "generator", "title", "metric", "gate_set", "x_axis", "statistic",
           "r_method", "extrapolated", "merged", "formulas", "removed", "seeds", "git_commit", "render_status",
           "derived_from", "replaced_by"]


def is_figure(path: Path) -> bool:
    if path.name == "all.tex" or path.name.endswith(".wrapper.tex") or "gallery" in path.parts:
        return False
    text = path.read_text()
    return "\\begin{tikzpicture}" in text and "\\documentclass" not in text


def _header(text: str) -> list[str]:
    out = []
    for line in text.splitlines():
        if not line.startswith("%"):
            break
        out.append(line[1:].strip())
    return out


def _legend_formulas(text: str, names: dict[str, str]) -> list[str]:
    """Scheme ids whose registry name starts a legend entry (LaTeX-escaped
    names compared after un-escaping)."""
    found = []
    for entry in re.findall(r"\\addlegendentry\{(.*)\}", text):
        e = entry.replace("\\&", "&").replace("\\_", "_")
        if any(s in e.lower() for s in STYLE_LEGENDS) and not any(e.startswith(n) for n in names.values()):
            continue
        for scheme, name in names.items():
            if e.startswith(name) and scheme not in found:
                found.append(scheme)
    return found


def describe(path: Path, root: Path, names: dict[str, str]) -> dict:
    """Attributes of one figure file (see module docstring)."""
    text = path.read_text()
    head = _header(text)
    hjoined = " ".join(head)
    rel = path.relative_to(root)
    parts = rel.parts
    rec = {c: "" for c in COLUMNS}
    rec["path"] = rel.as_posix()
    rec["slug"] = "__".join(parts)[: -len(".tex")]
    rec["experiment"] = parts[0]
    m = re.search(r"Generated by (pysimcount\.\w+)", hjoined)
    rec["generator"] = m.group(1) if m else ""
    m = re.search(r"figure: (.*?)(?: -- |$)(.*)", next((h for h in head if h.startswith("figure:")), ""))
    rec["title"] = (m.group(2) or m.group(1)).strip() if m else (head[1] if len(head) > 1 else path.stem)
    seed_dir = next((p for p in parts if re.fullmatch(r"seed\d+", p)), None)
    if "aggregate" in parts or re.search(r"over seeds|seeds \[", hjoined):
        rec["scope"] = "aggregate over seeds"
    elif seed_dir:
        rec["scope"] = seed_dir.replace("seed", "seed ")
    else:
        m = re.search(r"\bseed[= ](\d+)", hjoined)
        rec["scope"] = f"seed {m.group(1)}" if m else ""
    m = re.search(r"seeds (\[[\d, ]+\])", hjoined)
    rec["seeds"] = m.group(1) if m else (rec["scope"].replace("seed ", "") if rec["scope"].startswith("seed ") else "")
    m = re.search(r"metric=(\w+)", hjoined)
    if m:
        rec["metric"] = m.group(1)
    else:
        for cand in ("cnot", "total", "t"):
            if cand in parts[:-1] or path.stem.lower().startswith(cand + "-"):
                rec["metric"] = cand
                break
        if not rec["metric"] and path.stem.startswith("r-vs-n"):
            rec["metric"] = "r"
    m = re.search(r"gatebase=(\w+)", hjoined)
    rec["gate_set"] = m.group(1) if m else ("ct" if rec["metric"] == "t" else ("cz" if re.search(r"\bcz\b", hjoined) else ""))
    rec["x_axis"] = "eps" if "vs-eps" in path.stem or "vs eps" in hjoined else "n"
    if "median over seeds" in hjoined:
        rec["statistic"] = "median over seeds"
    elif "mean over seeds" in hjoined:
        rec["statistic"] = "mean over seeds"
    elif rec["scope"].startswith("seed"):
        rec["statistic"] = "single seed"
    m = re.match(r"A-(\w+)-by-order", path.stem)
    explicit = re.search(r"r_method=([\w-]+)", hjoined)
    if explicit:  # stated by the generator (pffig13, pffig13ext)
        rec["r_method"] = METHOD_NAMES.get(explicit.group(1), explicit.group(1))
    elif m:
        rec["r_method"] = METHOD_NAMES.get(m.group(1), m.group(1))
    elif path.stem.startswith("C-") and "by-bound" in path.stem:
        rec["r_method"] = "every bound + measured"
    elif "measured r" in hjoined or "measured" in hjoined:
        rec["r_method"] = "measured"
    rec["extrapolated"] = "yes" if re.search(r"fitted \$r\$|power-law fit|extrapolat", text) else "no"
    rec["merged"] = "merged" if re.search(r"\bmerged\b", hjoined) and "unmerged" not in hjoined else (
        "unmerged" if "unmerged" in hjoined or "unmerged" in parts else "")
    m = re.search(r"git_commit=(\w+)", hjoined)
    rec["git_commit"] = m.group(1)[:7] if m else ""
    found = _legend_formulas(text, names)
    if not found:
        # one-formula figures (legend by bound or by grouping) name the formula
        # in the file name (pffigure's C-<scheme>-by-bound) or in the header
        m = re.match(r"C-(.+)-by-bound$", path.stem)
        if m and m.group(1) in names:
            found = [m.group(1)]
        else:
            plain = hjoined.replace("\\&", "&")
            found = [k for k, name in names.items() if re.search(re.escape(name) + r"(?![\w=])", plain)]
    rec["formulas"] = ";".join(found)
    side = path.with_suffix(".json")
    if rec["generator"] == "pysimcount.pfchilds" and side.exists():
        s = json.loads(side.read_text())
        rec.update({"title": s["title"], "metric": s["metric"], "statistic": "mean over seeds",
                    "r_method": "measured + power-law fit (mean r)", "gate_set": "cz",
                    "formulas": ";".join(s["shown"]), "removed": ";".join(s["removed"]),
                    "seeds": str(s["seeds"]), "scope": "aggregate over seeds"})
    m = re.search(r"derived: (\S+\.tex) with (.+?) removed by pysimcount\.figdrop", hjoined)
    if m:  # a figdrop copy: same figure with one formula's series cut out
        rec["derived_from"] = (rel.parent / m.group(1)).as_posix()
        rec["title"] += f" (without {m.group(2)})"
    return rec


def link_derived(recs: list[dict]) -> None:
    """Mark each original that a figdrop copy replaces (``replaced_by``).
    Raises if a copy's original is not among ``recs``."""
    by_path = {r["path"]: r for r in recs}
    for r in recs:
        if r["derived_from"]:
            if r["derived_from"] not in by_path:
                raise ValueError(f"{r['path']}: original {r['derived_from']} not found")
            by_path[r["derived_from"]]["replaced_by"] = r["path"]


RQ_COLUMNS = ["rq_key", "rq_related", "rq_reasons"]
RQ_TIERS = ("related", "key")  # ascending: a figure keeps its highest tier per RQ


def load_rq(path: Path) -> dict:
    """Read and check the research-question relevance rules (see
    ``results/gallery/rq-relevance.json``). Raises on an unknown RQ, tier or
    manifest field, so a typo cannot silently match nothing."""
    cfg = json.loads(path.read_text())
    for i, rule in enumerate(cfg["rules"]):
        unknown = [q for q in rule["rq"] if q not in cfg["questions"]]
        if unknown:
            raise ValueError(f"rule {i}: unknown RQ {unknown}")
        if rule["tier"] not in RQ_TIERS:
            raise ValueError(f"rule {i}: tier must be one of {RQ_TIERS}, got {rule['tier']!r}")
        bad = [k for k in rule["match"] if k not in COLUMNS]
        if bad:
            raise ValueError(f"rule {i}: unknown manifest field(s) {bad}")
    return cfg


def _matches(rec: dict, match: dict) -> bool:
    for field, pattern in match.items():
        patterns = pattern if isinstance(pattern, list) else [pattern]
        if not any(fnmatch.fnmatchcase(rec[field], p) for p in patterns):
            return False
    return True


def assign_rq(recs: list[dict], cfg: dict) -> None:
    """Fill ``rq_key``, ``rq_related`` (``;``-joined RQ ids, in question
    order) and ``rq_reasons`` on every record. A figure matched by several
    rules for one RQ keeps the highest tier and every reason. A rule that
    matches no figure raises: it is stale or mistyped."""
    order = list(cfg["questions"])
    tiers = [{} for _ in recs]      # per record: rq -> tier index
    reasons = [[] for _ in recs]
    for i, rule in enumerate(cfg["rules"]):
        hit = False
        for j, rec in enumerate(recs):
            if not _matches(rec, rule["match"]):
                continue
            hit = True
            for q in rule["rq"]:
                tiers[j][q] = max(tiers[j].get(q, 0), RQ_TIERS.index(rule["tier"]))
                reasons[j].append(f"{q} {rule['tier']}: {rule['reason']}")
        if not hit:
            raise ValueError(f"rule {i} ({rule['rq']}, {rule['match']}) matches no figure")
    for rec, t, why in zip(recs, tiers, reasons):
        rec["rq_key"] = ";".join(q for q in order if t.get(q) == RQ_TIERS.index("key"))
        rec["rq_related"] = ";".join(q for q in order if t.get(q) == RQ_TIERS.index("related"))
        rec["rq_reasons"] = " | ".join(why)


MAIN_KINDS = ("figure", "table", "missing")
MAIN_STATUSES = ("ready", "update", "missing")


def load_main(path: Path, recs: list[dict], root: Path) -> dict:
    """Read and check the proposed main-body selection (``results/gallery/main-body.json``)
    and fill each record's ``main_body`` (``;``-joined "<section> <label>"). Raises on an
    unknown section, kind or status, a figure that is not on the page (absent, or replaced
    by a figdrop copy -- select the copy), a table file that does not exist, or a 'missing'
    item without a 'make' note."""
    cfg = json.loads(path.read_text())
    by_path = {r["path"]: r for r in recs}
    for r in recs:
        r["main_body"] = ""
    for i, item in enumerate(cfg["items"]):
        where = f"main-body item {i} ({item.get('section')} {item.get('label')})"
        if item["section"] not in cfg["sections"]:
            raise ValueError(f"{where}: unknown section")
        if item["kind"] not in MAIN_KINDS or item["status"] not in MAIN_STATUSES:
            raise ValueError(f"{where}: kind must be one of {MAIN_KINDS}, status one of {MAIN_STATUSES}")
        if (item["kind"] == "missing") != (item["status"] == "missing"):
            raise ValueError(f"{where}: kind and status must both be 'missing' or neither")
        if item["kind"] == "figure":
            rec = by_path.get(item["path"])
            if rec is None:
                raise ValueError(f"{where}: {item['path']} is not a figure in the manifest")
            if rec["replaced_by"]:
                raise ValueError(f"{where}: {item['path']} is shown through {rec['replaced_by']}; select that")
            tag = f"{item['section']} {item['label']}"
            rec["main_body"] = f"{rec['main_body']};{tag}" if rec["main_body"] else tag
        elif item["kind"] == "table":
            for key in ("path", "image", "tex"):
                if key in item and not (root / item[key]).is_file():
                    raise ValueError(f"{where}: {key} {item[key]} does not exist")
        elif not item.get("make"):
            raise ValueError(f"{where}: a missing item needs a 'make' note")
    return cfg


def render_all(recs: list[dict], root: Path, out: Path, jobs: int) -> None:
    def one(rec: dict) -> None:
        tex = root / rec["path"]
        png = out / "rendered" / f"{rec['slug']}.png"
        if png.exists() and png.stat().st_mtime >= tex.stat().st_mtime:
            rec["render_status"] = "ok"
            return
        tmp = out / "rendered" / rec["slug"]
        try:
            pdf, made = render_tex(tex, tmp)
            pdf.replace(out / "rendered" / f"{rec['slug']}.pdf")
            made.replace(png)
            tmp.rmdir()
            rec["render_status"] = "ok"
        except Exception as e:  # recorded per figure and printed; the run still fails at the end
            rec["render_status"] = f"failed: {type(e).__name__}: {e}"[:300]

    (out / "rendered").mkdir(parents=True, exist_ok=True)
    with ThreadPoolExecutor(max_workers=jobs) as pool:
        list(pool.map(one, recs))


