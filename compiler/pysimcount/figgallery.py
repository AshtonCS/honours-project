    for rec, p in zip(recs, paths):
        rec["header"] = " | ".join(_header(p.read_text()))
        rank = p.with_name(p.stem + "-ranking.md")
        rec["ranking"] = rank.relative_to(root).as_posix() if rank.exists() else ""
    link_derived(recs)
    assign_rq([r for r in recs if not r["derived_from"]], rq_cfg)
    by_path = {r["path"]: r for r in recs}
