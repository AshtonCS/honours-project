"""Run the upstream C++ (Time_Evolution) and record its output as fixtures.

The tests replay ``fixtures/upstream_operator_errors.json`` and
``fixtures/upstream_fields.json``; Docker is needed only to regenerate them:

    python -m effts.reference            # rebuild both fixtures

Container: a throwaway ``ubuntu:22.04`` named ``effts-ref`` with g++ 11,
Eigen 3.4.0 and HDF5 from apt, holding upstream ``Code/Time_Evolution``
(commit below) built with its own CMakeLists in Release mode, unmodified.
Recreate it with the commands in ``README.md``.

What is recorded.  Upstream ``error_estimate`` with ``method = operator``
prints ``Error at step k: <value>`` for k = 1..N_steps, after ``Trotter``'s
constructor has left ``cout`` in ``fixed`` / ``setprecision(20)``; so each
value carries 20 decimal places.  These lines are parsed from stdout; the
HDF5 file it also writes is discarded.

Fields.  Upstream ``hmag = random`` draws from ``std::mt19937(42)`` through
``std::uniform_real_distribution(-0.1, 0.1)``.  That distribution's algorithm
is left to the C++ library, so the values depend on libstdc++ vs libc++.
``upstream_fields.json`` records both, generated by a copy of upstream's
``generate_random_vector`` (``FIELD_PROGRAM`` below).  The parity cases pass
explicit fields, so they do not depend on this.
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
from pathlib import Path

from . import schemes as S

UPSTREAM_COMMIT = "1a5a16839dd32369f8a4db06b2568bfe087e335a"
CONTAINER = "effts-ref"
BINARY = "/src/Time_Evolution/build/main"
FIXTURES = Path(__file__).resolve().parent / "fixtures"
OPERATOR_FIXTURE = FIXTURES / "upstream_operator_errors.json"
FIELDS_FIXTURE = FIXTURES / "upstream_fields.json"

# Verbatim copy of upstream generate_random_vector (InOut.cpp, with the
# defaults from InOut.h: min -0.1, max 0.1, seed 42), printing 17 digits.
FIELD_PROGRAM = r"""
#include <random>
#include <cstdio>
template <typename RealT>
void gen(int size, RealT min = -0.1, RealT max = 0.1, int seed = 42) {
    std::mt19937 gen(seed);
    std::uniform_real_distribution<RealT> dist(min, max);
    for (int i = 0; i < size; ++i) printf(i ? ",%.17g" : "%.17g", (double)dist(gen));
    printf("\n");
}
int main() { for (int L = 2; L <= 12; ++L) gen<double>(L); }
"""

# Fields used by every parity case: upstream's own seed-42 values from
# libstdc++ (the Linux default), sliced to length L.  Filled from the
# fields fixture so the cases and the record cannot drift apart.


def _fields(L: int, library: str = "libstdc++") -> list[float]:
    data = json.loads(FIELDS_FIXTURE.read_text())
    return data[library][str(L)]


def parity_cases() -> list[dict]:
    """The cases recorded against upstream.  Small, but covering every branch:
    both groupings, three model classes, open and periodic boundaries, odd and
    even q, L = 2 (double-counted bond), and every Fig. 5 scheme."""
    cases = []
    fig5 = S.figure5_schemes() + [S.highest_q14()]
    for grouping in ("global", "local"):
        for s in fig5:
            cases.append(dict(model="XXZ", L=6, J=1.0, periodic=True, grouping=grouping,
                              scheme=s.name, t=10.0, n_steps=40))
    for grouping in ("global", "local"):
        for s in (S.forest_ruth(), S.recommended_q14()):
            cases.append(dict(model="XZ", L=5, J=1.0, periodic=False, grouping=grouping,
                              scheme=s.name, t=3.0, n_steps=15))
    cases.append(dict(model="Heisenberg", L=4, J=[1.0, 0.5, -0.7], periodic=True, grouping="local",
                      scheme=S.blanes_moan(6).name, t=2.0, n_steps=10))
    cases.append(dict(model="XXZ", L=2, J=1.0, periodic=True, grouping="global",
                      scheme=S.leapfrog().name, t=1.0, n_steps=5))
    return cases


def scheme_by_name(name: str) -> S.Scheme:
    pool = S.figure5_schemes() + [S.highest_q14(), S.blanes_moan(6)]
    for s in pool:
        if s.name == name:
            return s
    raise LookupError(name)


def input_file(case: dict) -> str:
    """Upstream input text for one case.

    Section headers must match exactly: upstream's reader stops the model block
    at '# Time evolution parameters' and the header block at
    '# General parameters'.  ``group = true`` selects upstream's *local*
    branch (see evolution.py).
    """
    s = scheme_by_name(case["scheme"])
    a_file, b_file = S.to_file_notation(s)
    model = {"XXZ": "ModelXXZ", "XZ": "ModelXZ", "Heisenberg": "ModelHeisenberg"}[case["model"]]
    J = case["J"]
    J_text = ", ".join(repr(float(j)) for j in J) if isinstance(J, list) else repr(float(J))
    fields = _fields(case["L"])
    return "\n".join([
        "# Routine (0 - Time evolution, 1 - Error estimation)",
        "routine = 1",
        "save_file = /tmp/effts_out.h5",
        "# Model parameters",
        f"model = {model}",
        f"L = {case['L']}",
        f"bound = {'false' if case['periodic'] else 'true'}",
        f"J = {J_text}",
        "hmag = " + ", ".join(repr(h) for h in fields),
        "# Time evolution parameters",
        "",
        "# General parameters",
        "method = operator",
        f"t = {case['t']!r}",
        f"N_steps = {case['n_steps']}",
        f"q = {s.q}",
        f"group = {'true' if case['grouping'] == 'local' else 'false'}",
        "imag_time = false",
        "a_vec = " + ", ".join(repr(x) for x in a_file),
        "b_vec = " + ", ".join(repr(x) for x in b_file),
        "",
    ])


_ERR_RE = re.compile(r"Error at step (\d+): ([0-9.eE+-]+)")


def run_case(case: dict) -> list[float]:
    text = input_file(case)
    subprocess.run(["docker", "exec", "-i", CONTAINER, "bash", "-c", "cat > /tmp/effts.in"],
                   input=text, text=True, check=True)
    out = subprocess.run(["docker", "exec", CONTAINER, BINARY, "/tmp/effts.in", "double"],
                         capture_output=True, text=True, check=True).stdout
    errs = {int(k): float(v) for k, v in _ERR_RE.findall(out)}
    if sorted(errs) != list(range(1, case["n_steps"] + 1)):
        raise RuntimeError(f"expected {case['n_steps']} error lines, got {len(errs)}:\n{out[-2000:]}")
    return [errs[k] for k in range(1, case["n_steps"] + 1)]


def regenerate_fields() -> None:
    """Record upstream's seed-42 fields under libstdc++ (container) and libc++ (host)."""
    out = {}
    subprocess.run(["docker", "exec", "-i", CONTAINER, "bash", "-c",
                    "cat > /tmp/fields.cpp && g++ -O2 -o /tmp/fields /tmp/fields.cpp"],
                   input=FIELD_PROGRAM, text=True, check=True)
    lines = subprocess.run(["docker", "exec", CONTAINER, "/tmp/fields"],
                           capture_output=True, text=True, check=True).stdout.split()
    out["libstdc++"] = {str(L): [float(x) for x in ln.split(",")] for L, ln in zip(range(2, 13), lines)}
    try:
        tmp = Path("/tmp") if sys.platform != "darwin" else Path(subprocess.run(
            ["getconf", "DARWIN_USER_TEMP_DIR"], capture_output=True, text=True).stdout.strip())
        src, exe = tmp / "effts_fields.cpp", tmp / "effts_fields"
        src.write_text(FIELD_PROGRAM)
        subprocess.run(["clang++", "-std=c++17", "-O2", "-o", str(exe), str(src)], check=True)
        lines = subprocess.run([str(exe)], capture_output=True, text=True, check=True).stdout.split()
        out["libc++"] = {str(L): [float(x) for x in ln.split(",")] for L, ln in zip(range(2, 13), lines)}
    except (OSError, subprocess.CalledProcessError) as e:  # host compiler is optional
        print(f"libc++ fields not recorded: {e}", file=sys.stderr)
    out["_source"] = ("upstream generate_random_vector (InOut.cpp) with InOut.h defaults "
                      f"(-0.1, 0.1, seed 42), commit {UPSTREAM_COMMIT}; double")
    FIELDS_FIXTURE.write_text(json.dumps(out, indent=1))


def regenerate_operator_errors() -> None:
    gxx = subprocess.run(["docker", "exec", CONTAINER, "g++", "--version"],
                         capture_output=True, text=True, check=True).stdout.splitlines()[0]
    records = []
    for case in parity_cases():
        print(f"  {case['model']:10s} L={case['L']} {case['grouping']:6s} {case['scheme'][:40]}", file=sys.stderr)
        records.append(dict(case=case, input=input_file(case), errors=run_case(case)))
    OPERATOR_FIXTURE.write_text(json.dumps(dict(
        _source=f"upstream Code/Time_Evolution @ {UPSTREAM_COMMIT}, Release build, {gxx}, "
                "Eigen 3.4.0, run with scalar type 'double', method = operator",
        records=records), indent=1))


if __name__ == "__main__":
    FIXTURES.mkdir(exist_ok=True)
    regenerate_fields()
    regenerate_operator_errors()
    print(f"wrote {FIELDS_FIXTURE} and {OPERATOR_FIXTURE}")
